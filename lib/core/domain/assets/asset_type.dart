/// [재화 구조 정리 및 재연결] Fortune Fusion 화면 분류(FeatureScope) 정의.
///
/// 이 앱의 최종 자산 구조는 2개뿐이다 — **프리패스(시간제 이용권)** +
/// **복주머니(단일 재화)**. "운세는 프리패스로 열고, 결제/커뮤니티는 모두
/// 복주머니로 움직인다."
///
/// [정리 이력] 과거에는 여기에 `AssetType` 열거형(openPass/happyMoney/
/// luckPouch)이 있어 "3대 자산" 체계로 문서화되어 있었다. 그러나
/// `happyMoney`(상점용)와 `luckPouch`(커뮤니티용)는 둘 다 주석상 "복주머니"로
/// 표기되면서도 서로 다른 식별자를 쓰는 **같은 재화의 중복 표현**이었고,
/// 실제 코드 어디에서도 `AssetType`/`primaryAsset`을 참조하지 않는 죽은
/// 정의였다(복주머니 잔액은 이미 [WalletProvider] 단일 원장으로 통합됨).
/// 최종 2-자산 구조 정리에 맞춰 `AssetType`은 제거하고, 실제로 쓰이는
/// [FeatureScope](화면 분류자)만 남긴다.
library;

/// 화면/기능을 3개 군으로 분리하는 판별자. 화면은 반드시 하나의 [FeatureScope]에
/// 귀속된다. fortune만 프리패스로 게이트되며, community/shop은 진입 자체를
/// 막지 않고 화면 내부에서 복주머니 적립/소비가 이루어진다.
enum FeatureScope {
  /// 운세군(오늘의 운세/타로/사주/궁합/관상·손금/테마 운세/운세 리포트) —
  /// 프리패스로 게이트.
  fortune,

  /// 커뮤니티군(소원게시판/소원방/부적만들기/커뮤니티/고민상담/반응·응원·공감) —
  /// 복주머니로 적립/소비.
  community,

  /// 상점/프리미엄군(복주머니 충전/프리패스 구매/구독/상품권/프리미엄 패키지) —
  /// 복주머니로 결제.
  shop,
}
