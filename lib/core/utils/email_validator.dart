/// 이메일 형식 검증 유틸리티.
///
/// [신통방통 이메일 회원가입 오류 수정 지시서] 기존에는 이메일 입력값에
/// 대한 형식 검사가 전혀 없어 `abc`, `abc123`, `abc@` 같은 값도 그대로
/// 서버로 전송되어 가입이 가능했다. 이 클래스는 클라이언트(즉시 피드백)와
/// 서버(최종 방어선, admin_web `signup/route.ts`) 양쪽에서 동일한 기준을
/// 쓸 수 있도록 정규식 패턴을 문서화해둔다(Dart/TypeScript 각자 구현이지만
/// 패턴은 반드시 동일하게 유지할 것).
///
/// [검증 기준] RFC 5322를 완벽히 구현하지는 않는다(그러면 지나치게
/// 복잡해지고, 실수로 정상 이메일을 막을 위험이 커진다). 대신 실무에서
/// 널리 쓰이는 "로컬파트@도메인.최상위도메인(영문 2자 이상)" 패턴을
/// 요구한다:
///   - '@' 앞에 1자 이상의 허용 문자(영문/숫자/일부 특수기호)
///   - '@' 뒤에 도메인 라벨이 1개 이상 이어지고, 마지막 라벨(TLD)은
///     반드시 영문 2자 이상이어야 한다.
///
/// 예) user@example.com ✅ / abc ❌(계정만 있음) / abc123 ❌('@' 없음) /
///     abc@ ❌(도메인 없음) / abc@example ❌(TLD 없음)
class EmailValidator {
  EmailValidator._();

  static final RegExp _pattern = RegExp(
    r'^[a-zA-Z0-9.!#$%&*+/=?^_`{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*\.[a-zA-Z]{2,}$',
  );

  /// 이메일 형식이 올바르면 true, 아니면 false.
  static bool isValid(String email) => _pattern.hasMatch(email.trim());

  /// 형식이 잘못됐을 때 사용자에게 보여줄 표준 에러 메시지.
  static const String errorMessage = '올바른 이메일 주소를 입력해 주세요.';
}
