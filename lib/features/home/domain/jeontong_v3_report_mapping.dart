/// 선택된 69종 카테고리 제목으로부터 `/saju/v3/report`용 질문 문장을
/// 자동 생성한다(1차 구현 — 별도 질문 입력창 없음, 사용자 승인).
///
/// "~에 대해 궁금해요" 형태로 고정해, 카테고리 제목 마지막 글자의 받침
/// 유무에 관계없이 항상 자연스러운 조사 없는 문장이 되게 한다.
String jeontongAutoQuestionForCategory(String categoryTitle) {
  return '$categoryTitle에 대해 궁금해요';
}
