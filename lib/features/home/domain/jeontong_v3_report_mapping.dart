// - G(건강)/H(개운·풍수)/E(궁합) 3개 대카테고리, 도합 20종은 9 PART 중 어느 것에도
//   자연스럽게 맞지 않는다(9 PART는 인생/재물/직업/관계/시기 축으로 짜여
//   있고, 건강·궁합·개운 아이템 축이 아니다) — 이 경우 매핑값은 null이며,
//   화면은 9 PART 뒤에 별도의 "선택 주제 심층 분석" 블록으로 붙인다
//   (사용자 승인 "옵션 B").
import 'jeontong_input.dart';
import '../../fortune/saju_v3/domain/birth_input.dart';

/// [JeontongInput → BirthInput] 필드 1:1 이동.
///
/// - `birthDateTimeLocal`은 이미 KST 벽시계 시각이므로 그대로 year/month/
///   day/hour/minute로 분해한다(별도 UTC 변환 불필요 — 백엔드도 KST 벽시계
///   값을 그대로 받는 계약).
/// - `gender`는 'M'/'F' → 'male'/'female'로만 변환한다(원본 계산 로직이
///   내부적으로 쓰는 'M'|'F'와 다른, 백엔드 계약 표기 차이일 뿐).
/// - [알려진 한계 — 백엔드 미지원] 백엔드 `BirthInput`(Pydantic)에는 윤달
///   (leap month) 필드가 없다. 로컬 [JeontongInput.isLeapMonth]는 여기서
///   버려진다 — 백엔드 변경이 금지되어 있어 고칠 수 없는, 추적된 한계다.
BirthInput jeontongInputToBirthInput(JeontongInput input) {
  final local = input.birthDateTimeLocal;
  return BirthInput(
    name: input.normalizedName,
    year: local.year,
    month: local.month,
    day: local.day,
    hour: local.hour,
    minute: local.minute,
    gender: (input.gender == 'F' || input.gender == 'female')
        ? 'female'
        : 'male',
    isLunar: input.isLunar,
  );
}

