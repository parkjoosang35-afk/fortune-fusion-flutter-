import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { NextRequest } from 'next/server';
import { prisma } from '../src/lib/db';
import { signUserToken } from '../src/lib/user-auth';
import { grantOpenPass } from '../src/lib/open-pass-service';
import { beginResultAccess } from '../src/lib/result-access-service';
import { POST } from '../src/app/api/public/fortune/tarot/route';
import { GET } from '../src/app/api/public/fortune/tarot/history/route';

async function main() {
  assert.equal(process.env.REGRESSION_LOCAL_DB, '1', '샌드박스 DB에서만 REGRESSION_LOCAL_DB=1로 실행하세요');
  assert.ok(process.env.DATABASE_URL?.includes('/home/user/workspace/'), '운영 DB에서 실행할 수 없습니다');
  const suffix = randomUUID().slice(0, 8);
  const user = await prisma.user.create({ data: { email: `tarot_reg_${suffix}@example.com`, nickname: `tarot_reg_${suffix}`, passwordHash: 'test' } });
  const policy = await prisma.passPolicy.create({ data: { name: `타로검증 ${suffix}`, passType: 'event', durationMin: 1, grantCount: 4, validityDays: 1, isActive: false } });
  const { userPass } = await grantOpenPass({ userId: user.id, policyId: policy.id, sourceType: 'test_mode' });
  await prisma.wallet.create({ data: { userId: user.id, currencyType: 'POINT', balance: 0 } });
  const token = await signUserToken({ userId: user.id, nickname: user.nickname });
  const previousTemplates = await prisma.aiPromptTemplate.findMany({ where: { fortuneTypeOrDomain: 'tarot', isActive: true } });
  const originalFetch = globalThis.fetch;
  let llmCalls = 0;
  let failLlm = false;
  globalThis.fetch = async () => {
    llmCalls++;
    await new Promise(resolve => setTimeout(resolve, 80));
    return new Response(JSON.stringify(failLlm ? { error: { message: '테스트 실패' } } : { content: [{ type: 'text', text: '검증용 모의 해석: 현재 선택의 조건을 돌아보고 행동을 정리하세요.' }] }), { status: failLlm ? 503 : 200, headers: { 'Content-Type': 'application/json' } });
  };
  let templateId: number | undefined;
  const send = async (transactionId: string) => {
    const response = await POST(new NextRequest('http://localhost/api/public/fortune/tarot', { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ question: '앞으로 나의 전체 운세는 어떻게 될까요?', topic: 'regression_unmatched', spreadType: 'three_card', paymentMethod: 'FREEPASS', transactionId }) }));
    return { status: response.status, body: await response.json() };
  };
  const remaining = async () => (await prisma.userPass.findUniqueOrThrow({ where: { id: userPass.id } })).remainingCount;
  try {
    await prisma.aiPromptTemplate.updateMany({ where: { id: { in: previousTemplates.map(t => t.id) } }, data: { isActive: false } });
    const missingId = `tarot_missing_${suffix}`;
    await beginResultAccess({ userId: user.id, transactionId: missingId, contentType: 'tarot', paymentMethod: 'FREEPASS' });
    assert.equal(await remaining(), 3);
    const missing = await send(missingId);
    assert.equal(missing.status, 503);
    assert.equal(missing.body.reason, 'PROMPT_NOT_CONFIGURED');
    assert.equal(await remaining(), 4);
    assert.equal(await prisma.fortuneRequest.count({ where: { userId: user.id } }), 0);
    console.log('PASS: 프롬프트 미설정은 503, 선차감 복구, 성공 이력 생성 없음');
    const template = await prisma.aiPromptTemplate.create({ data: { fortuneTypeOrDomain: 'tarot', version: 9999, templateBody: '검증용 프롬프트', isActive: true } });
    templateId = template.id;
    const successId = `tarot_success_${suffix}`;
    await beginResultAccess({ userId: user.id, transactionId: successId, contentType: 'tarot', paymentMethod: 'FREEPASS' });
    const success = await send(successId);
    assert.equal(success.status, 200);
    assert.equal(success.body.data.positions.length, 3);
    assert.equal(await remaining(), 3);
    const saved = await prisma.fortuneRequest.findFirstOrThrow({ where: { userId: user.id }, include: { result: true } });
    assert.equal(saved.result?.resultText, success.body.data.summary);
    assert.deepEqual(JSON.parse(saved.result!.resultMeta!).positions, success.body.data.positions);
    const history = await GET(new NextRequest('http://localhost/api/public/fortune/tarot/history', { headers: { Authorization: `Bearer ${token}` } }));
    const historyBody = await history.json();
    assert.equal(historyBody.data.length, 1);
    assert.equal(historyBody.data[0].id, success.body.data.id);
    assert.equal(historyBody.data[0].summary, success.body.data.summary);
    console.log('PASS: 앱 게이트 pending 거래 이어처리, 응답↔DB↔이력 카드·해석 일치');
    const callsBeforeRetry = llmCalls;
    const retry = await send(successId);
    assert.equal(retry.status, 200);
    assert.equal(retry.body.data.id, success.body.data.id);
    assert.equal(llmCalls, callsBeforeRetry);
    assert.equal(await remaining(), 3);
    console.log('PASS: 성공 거래 재요청은 기존 결과 반환, 추가 생성·차감 없음');
    failLlm = true;
    const failureId = `tarot_failure_${suffix}`;
    await beginResultAccess({ userId: user.id, transactionId: failureId, contentType: 'tarot', paymentMethod: 'FREEPASS' });
    const failed = await send(failureId);
    assert.equal(failed.status, 500);
    assert.equal(await remaining(), 3);
    assert.equal(await prisma.fortuneRequest.count({ where: { userId: user.id } }), 1);
    assert.equal((await prisma.resultAccessTransaction.findUniqueOrThrow({ where: { transactionId: failureId } })).status, 'refunded');
    console.log('PASS: 모의 LLM 실패는 500, 횟수 복구, 가짜 성공 결과 없음');
    failLlm = false;
    const concurrentId = `tarot_concurrent_${suffix}`;
    await beginResultAccess({ userId: user.id, transactionId: concurrentId, contentType: 'tarot', paymentMethod: 'FREEPASS' });
    const callsBeforeConcurrent = llmCalls;
    const simultaneous = await Promise.all([send(concurrentId), send(concurrentId)]);
    assert.equal(simultaneous.filter(r => r.status === 200).length, 1);
    assert.equal(simultaneous.filter(r => r.status === 409).length, 1);
    assert.equal(llmCalls - callsBeforeConcurrent, 1);
    assert.equal(await remaining(), 2);
    console.log('PASS: 같은 거래 동시 생성은 한 건만 실행, 추가 호출은 409');
    console.log('타로 회귀검증 통과 — 실제 DB/라우트, LLM은 모의 응답이며 운영 실호출 검증 아님');
  } finally {
    globalThis.fetch = originalFetch;
    await prisma.aiPromptTemplate.updateMany({ where: { id: { in: previousTemplates.map(t => t.id) } }, data: { isActive: true } });
    await prisma.resultAccessTransaction.deleteMany({ where: { userId: user.id } });
    await prisma.fortuneResult.deleteMany({ where: { request: { userId: user.id } } });
    await prisma.fortuneRequest.deleteMany({ where: { userId: user.id } });
    await prisma.userPass.deleteMany({ where: { userId: user.id } });
    if (templateId) await prisma.aiPromptTemplate.delete({ where: { id: templateId } });
    await prisma.passPolicy.delete({ where: { id: policy.id } });
  }
}
main().then(() => process.exit(0)).catch(e => { console.error('TEST FAILED:', e); process.exit(1); });
